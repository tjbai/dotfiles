// generates one obsidian css snippet per palette, recoloring the AnuPpuccin theme
// in the scratch vault without touching its typography.
// run: bun build.ts [vault]   (default ~/auctor/scratch; writes .obsidian/snippets/anp-<name>.css)
//
// AnuPpuccin derives every color from 26 catppuccin slots (`--ctp-base`, `--ctp-red`,
// …), each read through an rgb-triplet hook `--ctp-custom-<slot>` that its style
// settings "custom flavor" fills. a snippet fills those hooks instead. catppuccin's
// greys are a straight line from base to text, so the ramp is rebuilt the same way
// from each palette's own bg/fg and keeps its tint. the accent (links, selection,
// active items) follows obsidian's --accent-h/s/l and takes the palette's blue,
// like the stylus themes' --link.
//
// light palettes scope to .theme-light and dark ones to .theme-dark, so one of
// each can be on at once and follow obsidian's light/dark mode.

import { homedir } from "node:os"
import { join } from "node:path"
import { type Palette, palettes as stylusPalettes } from "../firefox/stylus/ampcode/build.ts"

// zed's dark themes (.config/zed/settings.json), not in the stylus set.
const zedPalettes: Record<string, Palette> = {
	gruvboxhard: {
		label: "Gruvbox Dark Hard",
		scheme: "dark",
		bg: "#1d2021", bg1: "#282828", bg2: "#3c3836", bg3: "#504945",
		fg: "#ebdbb2", fgMuted: "#a89984", fgDim: "#928374",
		red: "#fb4934", green: "#b8bb26", yellow: "#fabd2f", blue: "#83a598",
		magenta: "#d3869b", cyan: "#8ec07c", orange: "#fe8019",
	},
	dragon: {
		label: "Kanagawa Dragon",
		scheme: "dark",
		bg: "#181616", bg1: "#1d1c19", bg2: "#282727", bg3: "#393836",
		fg: "#c5c9c5", fgMuted: "#a6a69c", fgDim: "#737c73",
		red: "#c4746e", green: "#8a9a7b", yellow: "#c4b28a", blue: "#8ba4b0",
		magenta: "#a292a3", cyan: "#8ea4a2", orange: "#b6927b",
	},
}

type RGB = [number, number, number]

const grey = ["subtext1", "subtext0", "overlay2", "overlay1", "overlay0", "surface2", "surface1", "surface0"]

function rgb(hex: string): RGB {
	const n = Number.parseInt(hex.slice(1), 16)
	return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

function mix(a: string | RGB, b: string | RGB, t: number): RGB {
	const x = typeof a === "string" ? rgb(a) : a
	const y = typeof b === "string" ? rgb(b) : b
	return [0, 1, 2].map((i) => Math.round(x[i] + (y[i] - x[i]) * t)) as RGB
}

function hsl([r, g, b]: RGB): [number, number, number] {
	const [R, G, B] = [r / 255, g / 255, b / 255]
	const max = Math.max(R, G, B)
	const min = Math.min(R, G, B)
	const l = (max + min) / 2
	const d = max - min
	if (d === 0) return [0, 0, Math.round(l * 100)]
	const s = d / (1 - Math.abs(2 * l - 1))
	const h = max === R ? ((G - B) / d) % 6 : max === G ? (B - R) / d + 2 : (R - G) / d + 4
	return [Math.round((h * 60 + 360) % 360), Math.round(s * 100), Math.round(l * 100)]
}

function css(p: Palette): string {
	const light = p.scheme === "light"
	// mantle (sidebar) and crust (code blocks, cards) sit below base. latte steps
	// toward its text; mocha toward black.
	const below = light ? p.fg : "#000000"
	// catppuccin's grey stops, base (0) to text (1): latte and mocha space them differently.
	const ramp = light ? [0.9, 0.8, 0.71, 0.61, 0.51, 0.41, 0.31, 0.21] : [0.89, 0.77, 0.66, 0.55, 0.44, 0.33, 0.22, 0.11]
	const slots: Record<string, RGB> = {
		rosewater: mix(p.orange, p.fg, 0.25),
		flamingo: mix(p.red, p.fg, 0.25),
		pink: mix(p.magenta, p.red, 0.4),
		mauve: rgb(p.magenta),
		red: rgb(p.red),
		maroon: mix(p.red, p.orange, 0.5),
		peach: rgb(p.orange),
		yellow: rgb(p.yellow),
		green: rgb(p.green),
		teal: rgb(p.cyan),
		sky: mix(p.cyan, p.blue, 0.35),
		sapphire: mix(p.cyan, p.blue, 0.65),
		blue: rgb(p.blue),
		lavender: mix(p.blue, p.magenta, 0.5),
		text: rgb(p.fg),
		...Object.fromEntries(ramp.map((t, i) => [grey[i], mix(p.bg, p.fg, t)])),
		base: rgb(p.bg),
		mantle: mix(p.bg, below, light ? 0.055 : 0.2),
		crust: mix(p.bg, below, light ? 0.115 : 0.4),
	}
	const [h, s, l] = hsl(rgb(p.blue))
	const decls = [
		...Object.entries(slots).map(([k, v]) => `  --ctp-custom-${k}: ${v.join(", ")};`),
		`  --accent-h: ${h};`,
		`  --accent-s: ${s}%;`,
		`  --accent-l: ${l}%;`,
	].join("\n")
	return `/* ${p.label} for AnuPpuccin. generated by ~/dev/dotfiles/obsidian/build.ts, don't edit. */
.theme-${p.scheme} {
${decls}
}
`
}

const vault = process.argv[2] ?? join(homedir(), "auctor/scratch")
const dir = join(vault, ".obsidian/snippets")
for (const [name, p] of Object.entries({ ...stylusPalettes, ...zedPalettes })) {
	await Bun.write(join(dir, `anp-${name}.css`), css(p))
	console.log(`wrote anp-${name}.css (${p.scheme})`)
}
